"""Generate docs/index.md from the frontmatter of every project doc."""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import uadr_lib as lib

INDEX_REL = "docs/index.md"
HEADER = """---
purpose: Generated catalogue of project documentation and when to read each doc.
read_when: The router did not name a doc for what you need. Pick single entries; never read every doc.
---
# Documentation index

Generated by `python3 .automation/uadr.py index` from each doc's frontmatter. Do not edit by hand.
Templates for docs that do not exist yet: [templates/README.md](templates/README.md).
"""


def project_docs(root: Path) -> list[str]:
    return [p for p in lib.markdown_files(root)
            if p.startswith("docs/") and not p.startswith(lib.TEMPLATES_REL + "/") and p != INDEX_REL]


def build(root: Path = lib.ROOT) -> str:
    groups: dict[str, list[tuple[str, dict]]] = {}
    for rel in project_docs(root):
        meta, _ = lib.parse_frontmatter((root / rel).read_text(encoding="utf-8"))
        parts = rel.split("/")
        group = parts[1] if len(parts) > 2 else "general"
        groups.setdefault(group, []).append((rel, meta))
    out = [HEADER]
    if not groups:
        out.append("\nNo project documentation has been written yet.\n")
    for group in sorted(groups):
        out.append(f"\n## {group}\n\n| Doc | Purpose | Read when | Status |\n| --- | --- | --- | --- |\n")
        for rel, meta in sorted(groups[group]):
            cell = lambda k: meta.get(k, "Legacy doc, not yet classified").replace("|", "\\|")
            link = rel[len("docs/"):]
            out.append(f"| [{link}]({link}) | {cell('purpose')} | {cell('read_when')} | {meta.get('status', 'legacy')} |\n")
    return "".join(out)


def main(argv: list[str], root: Path = lib.ROOT) -> int:
    ap = argparse.ArgumentParser(prog="uadr.py index", description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if the index is out of date")
    args = ap.parse_args(argv)
    path, content = root / INDEX_REL, build(root)
    if args.check:
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            print(f"{INDEX_REL} is out of date: run python3 .automation/uadr.py index")
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {INDEX_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
